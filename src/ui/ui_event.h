#pragma once

// ================= События кнопок =================
enum class ButtonEvent {
    PRESSED,    // палец только что коснулся
    RELEASED,   // палец отпущен
    HELD        // палец удерживается (для долгих нажатий)
};

// Тип функции-обработчика кнопки
using ButtonCallback = void(*)(ButtonEvent event);

// ================= События касания экрана =================
enum class TouchEvent {
    PRESSED,    // палец только что коснулся
    MOVED,      // палец двигается, координаты изменились
    RELEASED,   // палец отпущен
    NONE        // ничего не изменилось
};